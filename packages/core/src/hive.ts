  room: string;
  round: number;
  tick: number;
  phase: 'waiting' | 'playing' | 'won' | 'lost';
  remaining: number;
  score: number;
  target: number;
  title: string;
  players: HivePlayer[];
  nectar: HiveEntity[];
  hazards: HiveEntity[];
